#!/usr/bin/env python3
"""Column C (cached traffic; supplementary, NOT OpenRelay's method): paired MI355X configs, ours vs theirs on the same box.

Asked by Maks via the lead, 2026-11-22: "if we did not do that before, then try it and see what happens". Nothing in
results/experiments.jsonl measured prompt-cache reuse before this.

Both recipes are taken verbatim from the paired confirm run results/mxC1_s7_r1/20261122T061956Z/config.json: setup_cmd,
image digest, weights, env and launch line. Both launch lines already have --enable-prefix-caching and
--enable-prompt-tokens-details. Only the steps change: no GSM8K gate (both recipes were gated in mxC1), and no prefill
shot. The protocol cells are column C, traffic client, tokenizer-exact, 300 s scored + 60 s warmup.

  C1 fit    shared_prefix: 38 pool entries x 7,600 tokens = 288,800 tokens, ~0.30x the KV pool (974,307 ours /
            977,076 theirs, startup_facts of mxC1_s7_r1); suffix U(380, 3420), mean 1,900; design cached share ~80%.
  C1 evict  the same with 385 entries = 2.93M tokens, ~3.0x the pool: forces eviction. Two rates only.
  C2 agent  agent_session: start 6-8K, + the real previous reply + a 1-2K tool result per turn, 4 turns, 0.5-2 s think,
            output U(76, 684) per turn; sessions open-loop at rate / 4.

Boxes (4, parallel): seed 7 runs ours then theirs, seed 8 runs theirs then ours, so box warm-up and order effects do not
favour one recipe.
  python3 configs/mk_column_c.py      # writes configs/cc_{c1,c2,x,x2}_s{7,8}.json
"""
import copy
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "results/mxC1_s7_r1/20261122T061956Z/config.json"
OUT_IN, OUT_OUT = {"uniform": [380, 3420]}, {"uniform": [76, 684]}
C1 = dict(prefix_tokens=7600, suffix_dist=OUT_IN, output_dist=OUT_OUT)
WORK = {
    "c1fit": dict(workload="shared_prefix", params=dict(C1, prefix_pool=38), rates=[4.0, 5.0, 6.0, 7.5]),
    "c1evict": dict(workload="shared_prefix", params=dict(C1, prefix_pool=385), rates=[3.5, 4.5]),
    "c2agent": dict(workload="agent_session", params=dict(start_dist={"uniform": [6000, 8000]}, tool_dist={"uniform": [1000, 2000]},
                                                          output_dist=OUT_OUT, turns=4, think_s=[0.5, 2.0]), rates=[4.0, 5.0, 6.0, 7.5]),
}
BOXES = {"c1": ["c1fit", "c1evict"], "c2": ["c2agent"], "x": ["c1fit", "c2agent"], "x2": ["c1fit", "c2agent"]}
# Extension (launched 2026-11-22 ~10:20Z): on the first boxes ours passed the TOP rung 7.5 req/s on C1 fit (p95 0.46 s) and
# C2 (2.82 s) while theirs failed 7.5 on both (7.54 s / 12.2 s). So the knee search continues above 7.5 for ours and between
# 6 and 7.5 for theirs, same groups (group_tag), same seeds, on fresh boxes.
RATES_X = {"mx_recipe": {"c1fit": [9.0, 10.5, 12.0], "c2agent": [8.5, 9.5]}, "or_recipe": {"c1fit": [6.75], "c2agent": [6.75]}}
# Second extension (~10:55Z): ours failed 9.0 (C1; 359 in flight, p50 TTFT 22 s) and 8.5 (C2) on cc_x_s7; theirs passed
# 6.75 (C1 both seeds, C2 seed 8) AND passed 7.5 on C1 seed 7 (cc_c1_s7), failing it only on seed 8. So the C1 gap is
# narrower than the first halves showed: both recipes now run the SAME rungs, so the gap is measured cell for cell.
RATES_X2 = {n: {"c1fit": [7.0, 8.0, 8.5], "c2agent": [7.0, 8.0]} for n in ("mx_recipe", "or_recipe")}


def rates(box, n, w):
    return {"x": RATES_X, "x2": RATES_X2}[box][n][w] if box in ("x", "x2") else WORK[w]["rates"]
GROUP = {"mx_recipe": ("cache_ours_mi355x", "ours"), "or_recipe": ("cache_theirs_mi355x", "openrelay_recipe")}


def main():
    base = json.loads(SRC.read_text())
    srv = {s["name"]: s for s in base["servers"]}
    for box, works in BOXES.items():
        for seed in (7, 8):
            order = ["mx_recipe", "or_recipe"] if seed == 7 else ["or_recipe", "mx_recipe"]
            cfg = {k: copy.deepcopy(v) for k, v in base.items() if k != "servers"}
            cfg["label"] = f"cc_{box}_s{seed}"
            cfg["stage"] = "column-c-cached"
            cfg["note"] = (f"Column C (cached traffic, supplementary, NOT OpenRelay's method), seed {seed}, {', '.join(works)}: the same "
                           f"MI355X serves {' then '.join('ours' if n == 'mx_recipe' else 'theirs' for n in order)}. Recipes verbatim "
                           "from mxC1_s7_r1. Generated by configs/mk_column_c.py.")
            per = [sum(len(rates(box, n, w)) for w in works) * 6.6 + 10 for n in order]   # cells of 360 s + gaps, + engine start
            cfg["max_minutes"] = int(sum(per) + 25)
            cfg["budget_usd"] = round(cfg["max_minutes"] / 60 * 4.76 + 1, 1)
            cfg["servers"] = []
            for n in order:
                s = copy.deepcopy(srv[n])
                s["claim_group"], s["origin"] = GROUP[n]
                s["steps"] = [st for st in s["steps"] if st["type"] == "sh"]          # keep the cheap inspect step
                for w in works:
                    s["steps"].append(dict(type="protocol", name=f"protocol_{n}_{w}", client="traffic", column="C", group_tag=w,
                                           workload=WORK[w]["workload"], params=WORK[w]["params"], rates=rates(box, n, w),
                                           seeds=[seed], duration=300, prefill_shot=False))
                cfg["servers"].append(s)
            p = ROOT / "configs" / f"{cfg['label']}.json"
            p.write_text(json.dumps(cfg, indent=1) + "\n")
            print(p.relative_to(ROOT), cfg["max_minutes"], "min cap", cfg["budget_usd"], "USD cap")


if __name__ == "__main__":
    main()
