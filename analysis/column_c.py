#!/usr/bin/env python3
"""results/COLUMN_C.md + results/column_c.json: column C (cached traffic; supplementary, NOT OpenRelay's method).

Every column-C cell in results/protocol_rows.json (written by analysis/screen_report.py), per recipe x workload x rate x
seed, with both reads of prompt-cache reuse side by side:
  - usage: sum(usage.prompt_tokens_details.cached_tokens) / sum(prompt_tokens) over the scored window (last 300 s);
  - server: vLLM's prefix-cache counters (vllm:prefix_cache_hits_total / queries_total) over the steady window.
Price: our $/req at the cell's ACHIEVED rate (published $/h) against OpenRelay's Gemma 4 31B sync price for the cell's
REALIZED mean request, cached input at their cached rate ($0.007/1M, 1/10 of input). The per-recipe knee summary is the
highest offered rate at which every seed's cell passes (claims.json has the claim-rule version).

  python3 -I analysis/column_c.py      (run analysis/report.py first so protocol_rows.json is current)
"""
from __future__ import annotations

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
RES = ROOT / "results"
WORK = {"c1fit": "C1 fit (38 shared 7.6K prefixes = 0.30x KV pool)", "c1evict": "C1 evict (385 prefixes = 3.0x KV pool)",
        "c2agent": "C2 agent sessions (real replies re-sent, 4 turns)"}


def fmt(x, n=2):
    return "-" if x is None else (f"{x:.{n}f}" if isinstance(x, float) else str(x))


def main():
    rows = json.loads((RES / "protocol_rows.json").read_text())
    rows = rows if isinstance(rows, list) else rows.get("rows", [])
    cells = [r for r in rows if r.get("column") == "C"]
    out, L = [], ["# Column C: cached traffic (generated by analysis/column_c.py; do not edit)", "",
                  "Supplementary, **NOT OpenRelay's method**. Configs: `configs/mk_column_c.py`. Both recipes verbatim from mxC1, "
                  "prefix caching on in both; 300 s scored + 60 s warmup; SLO p95 TTFT < 4 s.", "",
                  "- **cached share (usage)**: sum of usage.prompt_tokens_details.cached_tokens / sum of prompt_tokens, scored window.",
                  "- **cached share (server)**: vLLM's prefix-cache hits / queries counters over the steady window.",
                  "- **x**: our $/req at the achieved rate (published $/h) / OpenRelay's Gemma 4 31B sync price for the cell's "
                  "realized mean request, cached input at their cached rate ($0.007/1M).", ""]
    for tag, title in WORK.items():
        L += [f"## {title}", "",
              "| recipe | rate | seed | run | pass | p95 TTFT s | TPOT p50 ms | achieved req/s | prompt mean | cached share (usage) | cached share (server) | our $/req | OpenRelay $/req at realized cache | x |",
              "|---|---|---|---|---|---|---|---|---|---|---|---|---|---|"]
        mine = [r for r in cells if str(r.get("claim_group", "")).endswith("_" + tag)]
        for r in sorted(mine, key=lambda r: ("theirs" in r["claim_group"], r["offered_rps"], r["seed"], r["run_id"])):
            who = "theirs" if "theirs" in r["claim_group"] else "ours"
            ours = r.get("usd_per_req_at_achieved")
            bar = r.get("price_bar_usd_per_req_cached_realized")
            rec = dict(workload=tag, recipe=who, rate=r["offered_rps"], seed=r["seed"], run_id=r["run_id"], slo_pass=r.get("slo_pass"),
                       ttft_p95_s=r.get("ttft_p95_s"), tpot_p50_s=r.get("tpot_p50_s"), achieved_rps=r.get("achieved_rps"),
                       prompt_tokens_mean=r.get("prompt_tokens_mean"), cached_share_usage=r.get("cached_share_scored"),
                       cached_share_server=r.get("server_prefix_cache_hit_ratio"), usd_per_req=ours, openrelay_cached_usd_per_req=bar,
                       ratio=(ours / bar) if (ours and bar) else None, file=r.get("file"))
            out.append(rec)
            L.append(f"| {who} | {r['offered_rps']} | {r['seed']} | `{r['run_id']}` | {'pass' if r.get('slo_pass') else '**fail**'} | "
                     f"{fmt(r.get('ttft_p95_s'))} | {fmt((r.get('tpot_p50_s') or 0) * 1000, 1) if r.get('tpot_p50_s') else '-'} | "
                     f"{fmt(r.get('achieved_rps'), 3)} | {fmt(r.get('prompt_tokens_mean'), 0)} | {fmt(rec['cached_share_usage'], 3)} | "
                     f"{fmt(rec['cached_share_server'], 3)} | {fmt(ours, 6)} | {fmt(bar, 6)} | {fmt(rec['ratio'], 3)} |")
        knees = []
        for who in ("ours", "theirs"):
            rs = [x for x in out if x["workload"] == tag and x["recipe"] == who]
            by = {}
            for x in rs:
                by.setdefault(x["rate"], []).append(x)
            seeds = {x["seed"] for x in rs}
            ok = [rate for rate, xs in by.items() if {x["seed"] for x in xs} == seeds and all(x["slo_pass"] for x in xs)]
            fail = [rate for rate, xs in by.items() if any(not x["slo_pass"] for x in xs)]
            knees.append(f"{who}: every seed passes up to {fmt(max(ok)) if ok else 'none'} req/s; lowest failing rate "
                         f"{fmt(min(fail)) if fail else 'none tested'} (seeds {sorted(seeds)})")
        L += ["", "- " + "\n- ".join(knees), ""]
    (RES / "column_c.json").write_text(json.dumps(dict(schema="column_c/1", note="supplementary, NOT OpenRelay's method", cells=out), indent=1))
    (RES / "COLUMN_C.md").write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
