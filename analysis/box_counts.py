#!/usr/bin/env python3
"""Per-box counts across every same-box paired test of Gemma 4 31B on MI355X (C1, C2, C2b): for each recipe and load
column, on how many boxes it held each rate (p95 time to first token < 4 s), out of the boxes that ran that rate.
These are COUNTS, not claims; claims stay per test group (analysis/screen_report.py). Written to results/BOX_COUNTS.md
and results/box_counts.json; bin/build_readme.py and docs/WRITEUP.md H1 read the numbers from here.

  python3 -I analysis/box_counts.py
"""
from __future__ import annotations

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
RES = ROOT / "results"
FAMILIES = {"final recipe (ours + MX_PS_FP4)": ("mx_stack_C2", "mx_stack_C2b"),
            "ours-today": ("mx_recipe_C1", "mx_recipe_C2", "mx_recipe_C2b"),
            "theirs (OpenRelay's recipe)": ("or_recipe_paired_C1", "or_recipe_paired_C2", "or_recipe_paired_C2b")}
RATES = (3.0, 3.25, 3.5, 3.75)


def counts(rows=None):
    rows = rows if rows is not None else json.loads((RES / "protocol_rows.json").read_text())
    rows = rows if isinstance(rows, list) else rows.get("rows", [])
    out = {}
    for fam, groups in FAMILIES.items():
        for col in ("A", "B"):
            cells = [r for r in rows if r.get("claim_group") in groups and r.get("column") == col]
            boxes = sorted({r["run_id"].split("/")[0] for r in cells})
            per = {}
            for rate in RATES:
                at = {}
                for r in cells:
                    if r.get("offered_rps") == rate:
                        b = r["run_id"].split("/")[0]
                        at[b] = at.get(b, True) and bool(r.get("slo_pass"))   # a box holds a rate if every cell there passed
                per[str(rate)] = dict(held=sum(at.values()), ran=len(at))
            out[f"{fam}|{col}"] = dict(family=fam, column=col, groups=list(groups), boxes=len(boxes), rates=per)
    return out


def main():
    c = counts()
    (RES / "box_counts.json").write_text(json.dumps(dict(schema="box_counts/1", note="counts, not claims", counts=c), indent=1))
    L = ["# Per-box counts, same-box paired tests C1 + C2 + C2b (generated by analysis/box_counts.py; do not edit)", "",
         "Boxes on which each recipe held each rate (p95 time to first token < 4 s), out of the boxes that ran it. Counts, "
         "not claims: the claims are per test group in [CLAIMS.md](CLAIMS.md).", ""]
    for col, name in (("A", "OpenRelay's client (random tokens)"), ("B", "real text")):
        L += [f"**{name}**", "", "| recipe | boxes | " + " | ".join(f"{r:g} req/s" for r in RATES) + " |", "|---|---|" + "---|" * len(RATES)]
        for fam in FAMILIES:
            v = c[f"{fam}|{col}"]
            L.append(f"| {fam} | {v['boxes']} | " + " | ".join(
                (f"{v['rates'][str(r)]['held']} of {v['rates'][str(r)]['ran']}" if v['rates'][str(r)]['ran'] else "not run") for r in RATES) + " |")
        L.append("")
    (RES / "BOX_COUNTS.md").write_text("\n".join(L))
    print("\n".join(L))


if __name__ == "__main__":
    main()
